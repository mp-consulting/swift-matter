#!/usr/bin/env python3
"""Regenerates Sources/Matter/Attestation/RegistryPAAs.swift from the Distributed Compliance Ledger.

The DCL is the CSA's registry of certified Matter products and of the Product Attestation Authorities (PAAs) whose
certificates root every production device's attestation chain (Core §6.2.2.1, §11.23). This does what connectedhomeip's
credentials/fetch_paa_certs_from_dcl.py does: list the approved root certificates, fetch each one, keep it as DER.

Usage: Scripts/update-trust-store.py [--test-net] > Sources/Matter/Attestation/RegistryPAAs.swift
"""
import base64
import json
import sys
import urllib.parse
import urllib.request

MAIN_NET = "https://on.dcl.csa-iot.org"
TEST_NET = "https://on.test-net.dcl.csa-iot.org"


def get(base, path):
    with urllib.request.urlopen(base + path, timeout=30) as response:
        return json.load(response)


def der(pem):
    body = "".join(line for line in pem.strip().splitlines() if not line.startswith("-----"))
    return base64.b64decode(body)


def main():
    base = TEST_NET if "--test-net" in sys.argv[1:] else MAIN_NET
    roots = get(base, "/dcl/pki/root-certificates")["approvedRootCertificates"]["certs"]
    certificates = {}
    for root in roots:
        subject = urllib.parse.quote(root["subject"], safe="")
        key_id = urllib.parse.quote(root["subjectKeyId"], safe="")
        for cert in get(base, f"/dcl/pki/certificates/{subject}/{key_id}")["approvedCertificates"]["certs"]:
            if cert.get("isRoot"):
                certificates[der(cert["pemCert"])] = cert.get("subjectAsText", "")
    if not certificates:
        sys.exit("The ledger listed no root certificates")

    print("// Generated by Scripts/update-trust-store.py from the Distributed Compliance Ledger (%s): do not edit." % base)
    print("// The approved Product Attestation Authorities' root certificates, as DER in base64.")
    print("")
    print("extension AttestationTrustStore {")
    print("    /// The %d PAA certificates the ledger approved when this file was generated." % len(certificates))
    print("    static let registryPAAs: [String] = [")
    for data, subject in sorted(certificates.items(), key=lambda item: (item[1], item[0])):
        print("        // %s" % subject.replace("\n", " "))
        print('        "%s",' % base64.b64encode(data).decode())
    print("    ]")
    print("}")


if __name__ == "__main__":
    main()
